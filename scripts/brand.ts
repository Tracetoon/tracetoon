/**
 * The Tracetoon logo kit: icon, wordmark and lockups for light and dark
 * backgrounds, as SVG and PNG, plus a favicon set and a social card.
 *
 *   bun scripts/brand.ts            write docs/brand/ (and src/brand/sources.ts)
 *   bun scripts/brand.ts --check    exit 1 when any file is out of date
 *   bun scripts/brand.ts --zip kit.zip   also pack the kit (every size) for a release
 *
 * Sources: docs/brand/src/icon.svg and wordmark.svg (Bangers lettering in
 * outlines). Everything else under docs/brand/ is generated; don't edit it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const OUT = 'docs/brand';
const SOURCES = 'src/brand/sources.ts';

/** src/brand/sources.ts: the raw sources as strings, so the binary carries them. */
export function sourcesTs(
  read = (p: string) => readFileSync(join(root, p), 'utf8'),
): string {
  const q = (s: string) => JSON.stringify(s.replace(/\r\n/g, '\n'));
  return `// Generated by scripts/brand.ts from docs/brand/src. Do not edit by hand.
export const ICON_SOURCE = ${q(read(`${OUT}/src/icon.svg`))};
export const WORDMARK_SOURCE = ${q(read(`${OUT}/src/wordmark.svg`))};
`;
}

/** Sizes committed to the repository; the release zip adds the larger ones. */
const ICON_SIZES = [64, 128, 256, 512];
const ICON_SIZES_ZIP = [1024];
const MARK_HEIGHTS = [128, 256];
const MARK_HEIGHTS_ZIP = [512];

/** A Windows .ico holding PNG images (supported since Vista; browsers read it). */
export function ico(pngs: { size: number; data: Uint8Array }[]): Buffer {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2); // icon
  head.writeUInt16LE(pngs.length, 4);
  let offset = head.length;
  pngs.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size >= 256 ? 0 : size, e);
    head.writeUInt8(size >= 256 ? 0 : size, e + 1);
    head.writeUInt16LE(1, e + 4); // planes
    head.writeUInt16LE(32, e + 6); // bits per pixel
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...pngs.map((p) => Buffer.from(p.data))]);
}

/** Every file of the kit: path under docs/brand -> contents; `zipOnly` marks the extra sizes. */
export async function brandKit(): Promise<
  Map<string, { data: string | Uint8Array; zipOnly?: boolean }>
> {
  const b = await import('../src/brand/index.ts');
  const { svgToPng } = await import('../src/comic/raster.ts');
  const out = new Map<string, { data: string | Uint8Array; zipOnly?: boolean }>();
  const svg = (path: string, data: string) => out.set(path, { data });
  const png = async (path: string, source: string, width: number, zipOnly = false) =>
    out.set(path, { data: await svgToPng(source, Math.round(width)), zipOnly });

  // Icon: plain (light/dark) and on tiles.
  const icons: Record<string, string> = {
    'tracetoon-icon': b.iconSvg('light'),
    'tracetoon-icon-dark': b.iconSvg('dark'),
    'tracetoon-icon-tile-dark': b.tileSvg('dark'),
    'tracetoon-icon-tile-light': b.tileSvg('light'),
  };
  for (const [name, source] of Object.entries(icons)) {
    svg(`${name}.svg`, source);
    for (const s of ICON_SIZES) await png(`png/${name}-${s}.png`, source, s);
    for (const s of ICON_SIZES_ZIP) await png(`png/${name}-${s}.png`, source, s, true);
  }

  // Wordmark and lockups, by height.
  const marks: Record<string, string> = {
    'tracetoon-wordmark': b.wordmarkSvg(),
    'tracetoon-lockup': b.lockupSvg('light', 'row'),
    'tracetoon-lockup-dark': b.lockupSvg('dark', 'row'),
    'tracetoon-lockup-stacked': b.lockupSvg('light', 'stacked'),
    'tracetoon-lockup-stacked-dark': b.lockupSvg('dark', 'stacked'),
  };
  for (const [name, source] of Object.entries(marks)) {
    svg(`${name}.svg`, source);
    const a = b.aspect(source);
    for (const h of MARK_HEIGHTS) await png(`png/${name}-${h}h.png`, source, h * a);
    for (const h of MARK_HEIGHTS_ZIP)
      await png(`png/${name}-${h}h.png`, source, h * a, true);
  }

  // Favicons and app icons.
  svg('favicon/favicon.svg', b.iconSvg('auto'));
  const fav: { size: number; data: Uint8Array }[] = [];
  for (const s of [16, 32, 48]) {
    const data = await svgToPng(b.iconSvg('light'), s);
    fav.push({ size: s, data });
    out.set(`favicon/favicon-${s}.png`, { data });
  }
  out.set('favicon/favicon.ico', { data: ico(fav) });
  await png(
    'favicon/apple-touch-icon.png',
    b.tileSvg('light', 1024, 0.08).replace(/rx="[^"]+"/, 'rx="0"'),
    180,
  );
  await png('favicon/icon-192.png', b.tileSvg('light'), 192);
  await png('favicon/icon-512.png', b.tileSvg('light'), 512);
  // Maskable: full-bleed background, art inside the 80% safe zone.
  await png(
    'favicon/icon-maskable-512.png',
    b.tileSvg('light', 1024, 0.18).replace(/rx="[^"]+"/, 'rx="0"'),
    512,
  );
  svg(
    'favicon/site.webmanifest',
    JSON.stringify(
      {
        name: 'Tracetoon',
        short_name: 'Tracetoon',
        icons: [
          { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
          {
            src: '/icon-maskable-512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
        theme_color: b.BRAND.ink,
        background_color: b.BRAND.cream,
        display: 'browser',
      },
      null,
      2,
    ) + '\n',
  );

  // Social card (GitHub social preview, og:image): 1280x640.
  const card = socialCard(b);
  svg('tracetoon-social.svg', card);
  await png('tracetoon-social.png', card, 1280);
  return out;
}

function socialCard(b: typeof import('../src/brand/index.ts')): string {
  const W = 1280;
  const H = 640;
  const lock = b.lockupSvg('light', 'row');
  const lw = 940;
  const lh = lw / b.aspect(lock);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Tracetoon: PRs with receipts. And comics.">
  <defs>
    <pattern id="cdots" width="22" height="22" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><circle cx="11" cy="11" r="4" fill="${b.BRAND.ink}" fill-opacity=".07"/></pattern>
    <linearGradient id="cfade" x1="0" y1="0" x2="1" y2="1"><stop offset=".55" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff"/></linearGradient>
    <mask id="cmask"><rect width="${W}" height="${H}" fill="url(#cfade)"/></mask>
  </defs>
  <rect width="${W}" height="${H}" fill="${b.BRAND.cream}"/>
  <rect width="${W}" height="${H}" fill="url(#cdots)" mask="url(#cmask)"/>
  <rect x="44" y="44" width="${W - 88}" height="${H - 88}" rx="18" fill="none" stroke="${b.BRAND.ink}" stroke-width="8"/>
  ${b.nest(b.prefixIds(lock, 'l'), (W - lw) / 2, 120, lw, lh)}
  <text x="${W / 2}" y="${120 + lh + 92}" text-anchor="middle" font-family="Comic Neue" font-weight="700" font-size="60" fill="${b.BRAND.ink}">PRs with receipts. And comics.</text>
  <text x="${W / 2}" y="${H - 84}" text-anchor="middle" font-family="Comic Neue" font-weight="700" font-size="30" fill="#5a5548">tracetoon.ai</text>
</svg>
`;
}

/** Files under the repository root -> expected contents (the committed set). */
export async function expected(): Promise<Map<string, string | Uint8Array>> {
  const files = new Map<string, string | Uint8Array>([[SOURCES, sourcesTs()]]);
  const kit = await brandKit();
  for (const [path, f] of kit) if (!f.zipOnly) files.set(`${OUT}/${path}`, f.data);
  // The catalog icon every plugin manifest points at (ICON in scripts/agent-surfaces.ts).
  files.set(
    'plugin/assets/tracetoon.svg',
    kit.get('tracetoon-icon-tile-dark.svg')?.data ?? '',
  );
  return files;
}

const same = (a: string | Uint8Array, b: Buffer) =>
  typeof a === 'string'
    ? a === b.toString('utf8').replace(/\r\n/g, '\n')
    : Buffer.from(a).equals(b);

if (import.meta.main) {
  const args = process.argv.slice(2);
  // The brand module imports sources.ts; refresh it first so this run sees the current sources.
  if (!args.includes('--check')) writeFileSync(join(root, SOURCES), sourcesTs());
  const files = await expected();
  if (args.includes('--check')) {
    const stale = [...files].filter(
      ([p, d]) => !existsSync(join(root, p)) || !same(d, readFileSync(join(root, p))),
    );
    if (stale.length) {
      console.error(
        `Out of date (run bun scripts/brand.ts):\n  ${stale.map(([p]) => p).join('\n  ')}`,
      );
      process.exit(1);
    }
    console.log(`Brand kit is current (${files.size} files).`);
  } else {
    for (const [p, d] of files) {
      mkdirSync(dirname(join(root, p)), { recursive: true });
      writeFileSync(join(root, p), d);
    }
    console.log(`Wrote ${files.size} brand files.`);
  }
  const zi = args.indexOf('--zip');
  if (zi >= 0) {
    const target = args[zi + 1];
    if (!target) throw new Error('--zip needs a file name');
    const { zip } = await import('./site-kit.ts');
    const kit = await brandKit();
    const readme = readFileSync(join(root, OUT, 'README.md'), 'utf8');
    const entries = [...kit].map(([p, f]) => ({
      name: `tracetoon-brand-kit/${p}`,
      data: typeof f.data === 'string' ? Buffer.from(f.data) : f.data,
    }));
    entries.push({ name: 'tracetoon-brand-kit/README.md', data: Buffer.from(readme) });
    entries.push({
      name: 'tracetoon-brand-kit/OFL-Bangers.txt',
      data: readFileSync(join(root, OUT, 'src', 'OFL-Bangers.txt')),
    });
    writeFileSync(target, zip(entries));
    console.log(`Packed ${entries.length} files into ${target}.`);
  }
}
